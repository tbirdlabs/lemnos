#!/usr/bin/env python3
# Writes core/tz_zones.inc: the time zones the web page offers, each with its POSIX TZ rule, taken from the IANA
# database (the footer line of each zone's TZif file, from Python's tzdata package: pip install tzdata).
# Run after changing ZONES; tools/test_core checks every rule against the database hour by hour.
#
#   py -3 tools/gen_tz.py

